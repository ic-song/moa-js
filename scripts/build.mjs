import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createHash } from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const grid = path.join(root, 'packages/grid');
const parts = [];
for (const name of ['model', 'data-view', 'clipboard', 'xlsx', 'grid']) parts.push((await readFile(path.join(grid, `src/${name}.js`), 'utf8')).replace(/^import .*;\r?\n/gm, ''));
const source = parts.join('\n');
const metadata = JSON.parse(await readFile(path.join(grid, 'package.json'), 'utf8'));
const banner = `/*! Moa JS Grid v${metadata.version} | MIT License | See LICENSE */\n`;
const plain = source.replace(/^export /gm, '');
await mkdir(path.join(grid, 'dist'), { recursive: true });
await writeFile(path.join(grid, 'dist/moa-grid.mjs'), banner + source + '\nexport default Grid;\n');
await writeFile(path.join(grid, 'dist/moa-grid.js'), banner + '(function () {\n\'use strict\';\n' + plain + '\nglobalThis.MoaGrid = Grid;\n})();\n');
await writeFile(path.join(grid, 'dist/moa-grid.cjs'), banner + "'use strict';\n" + plain + '\nmodule.exports = { Grid, GridModel, parseTSV, toTSV, readXLSX, writeXLSX };\n');
await copyFile(path.join(grid, 'src/grid.css'), path.join(grid, 'dist/moa-grid.css'));
await copyFile(path.join(root, 'LICENSE'), path.join(grid, 'LICENSE'));
const hashes = [];
for (const name of ['dist/moa-grid.js', 'dist/moa-grid.mjs', 'dist/moa-grid.cjs', 'dist/moa-grid.css', 'vendor/sheetjs/xlsx.full.min.js', 'vendor/sheetjs/LICENSE', 'LICENSE', 'THIRD_PARTY_NOTICES.md']) hashes.push(`${createHash('sha256').update(await readFile(path.join(grid, name))).digest('hex')}  ${name}`);
await writeFile(path.join(grid, 'SHA256SUMS.txt'), hashes.join('\n') + '\n');
console.log('Built browser JS, ESM, CommonJS, CSS and license without external dependencies.');
