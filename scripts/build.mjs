import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createHash } from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const grid = path.join(root, 'packages/grid');
const readText = async file => (await readFile(file, 'utf8')).replace(/\r\n?/g, '\n');
const parts = [];
for (const name of ['formula', 'model', 'data-view', 'clipboard', 'xlsx', 'virtual', 'grid']) parts.push((await readText(path.join(grid, `src/${name}.js`))).replace(/^import .*;\n/gm, ''));
const source = parts.join('\n');
const metadata = JSON.parse(await readFile(path.join(grid, 'package.json'), 'utf8'));
const banner = `/*! Moa JS Grid v${metadata.version} | MIT License | See LICENSE */\n`;
const plain = source.replace(/^export /gm, '');
await mkdir(path.join(grid, 'dist'), { recursive: true });
await writeFile(path.join(grid, 'dist/moa-grid.mjs'), banner + source + '\nexport default Grid;\n');
await writeFile(path.join(grid, 'dist/moa-grid.js'), banner + '(function () {\n\'use strict\';\n' + plain + '\nglobalThis.MoaGrid = Grid;\n})();\n');
await writeFile(path.join(grid, 'dist/moa-grid.cjs'), banner + "'use strict';\n" + plain + '\nmodule.exports = { Grid, GridModel, FormulaSheet, isFormula, translateFormula, columnName, parseTSV, toTSV, readXLSX, writeXLSX, virtualWindow, columnWindow };\n');
const compat = (await readText(path.join(grid, 'src/realgrid-compat.js'))).replace(/^import .*;\n/gm, '');
await writeFile(path.join(grid, 'dist/moa-realgrid.mjs'), banner + "import { Grid, GridModel } from './moa-grid.mjs';\n" + compat);
await writeFile(path.join(grid, 'dist/moa-realgrid.cjs'), banner + "const { Grid, GridModel } = require('./moa-grid.cjs');\n" + compat.replace(/^export /gm, '') + '\nmodule.exports = { LocalDataProvider, GridView, UnsupportedFeatureError, compatibility };\n');
await writeFile(path.join(grid, 'dist/moa-realgrid.js'), banner + '(function () {\n\'use strict\';\n' + plain + '\n' + compat.replace(/^export /gm, '') + '\nglobalThis.MoaRealGrid = { LocalDataProvider, GridView, UnsupportedFeatureError, compatibility };\n})();\n');
await writeFile(path.join(grid, 'dist/moa-grid.css'), await readText(path.join(grid, 'src/grid.css')));
await writeFile(path.join(grid, 'LICENSE'), await readText(path.join(root, 'LICENSE')));
const notices = path.join(grid, 'THIRD_PARTY_NOTICES.md');
await writeFile(notices, await readText(notices));
const hashes = [];
for (const name of ['dist/moa-grid.js', 'dist/moa-grid.mjs', 'dist/moa-grid.cjs', 'dist/moa-grid.css', 'dist/moa-realgrid.js', 'dist/moa-realgrid.mjs', 'dist/moa-realgrid.cjs', 'vendor/sheetjs/xlsx.full.min.js', 'vendor/sheetjs/LICENSE', 'LICENSE', 'THIRD_PARTY_NOTICES.md']) hashes.push(`${createHash('sha256').update(await readFile(path.join(grid, name))).digest('hex')}  ${name}`);
await writeFile(path.join(grid, 'SHA256SUMS.txt'), hashes.join('\n') + '\n');
console.log('Built browser JS, ESM, CommonJS, CSS and license without external dependencies.');
